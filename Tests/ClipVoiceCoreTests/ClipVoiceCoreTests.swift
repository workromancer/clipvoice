import XCTest
import AppKit
@testable import ClipVoiceCore

final class ClipVoiceCoreTests: XCTestCase {
    private func makeTempStoreURL() -> URL {
        let dir = FileManager.default.temporaryDirectory
            .appendingPathComponent("clipvoice-tests-\(UUID().uuidString)", isDirectory: true)
        return dir.appendingPathComponent("history.json", isDirectory: false)
    }

    func testStableIDInvarianceAcrossNewestFirstReorders() throws {
        let url = makeTempStoreURL()
        defer { try? FileManager.default.removeItem(at: url.deletingLastPathComponent()) }

        let store = ClipStore(fileURL: url)
        let r1 = store.ingest("https://github.com/workromancer/clipvoice")
        let r2 = store.ingest("swift test --parallel")
        let r3 = store.ingest("https://docs.swift.org/swift-book/")

        guard case .inserted(let c1) = r1,
              case .inserted(let c2) = r2,
              case .inserted(let c3) = r3 else {
            return XCTFail("Expected all 3 ingests to insert new items")
        }

        XCTAssertEqual(c1.id, "clip-1")
        XCTAssertEqual(c2.id, "clip-2")
        XCTAssertEqual(c3.id, "clip-3")

        // Newest-first order
        XCTAssertEqual(store.list().map(\.id), ["clip-3", "clip-2", "clip-1"])

        // Re-copying clip-1 bumps it to top while preserving its stable ID
        let bump = store.ingest("https://github.com/workromancer/clipvoice")
        guard case .bumpedExisting(let bumped) = bump else {
            return XCTFail("Expected duplicate ingest to bump existing item")
        }
        XCTAssertEqual(bumped.id, "clip-1")
        XCTAssertEqual(store.list().map(\.id), ["clip-1", "clip-3", "clip-2"])

        // Adding a 4th item assigns clip-4 and leaves existing IDs intact
        let r4 = store.ingest("fourth snippet")
        guard case .inserted(let c4) = r4 else {
            return XCTFail("Expected 4th insert")
        }
        XCTAssertEqual(c4.id, "clip-4")
        XCTAssertEqual(store.list().map(\.id), ["clip-4", "clip-1", "clip-3", "clip-2"])
    }

    func testSpeakableIDResolution() {
        let now = Date()
        let items = [
            ClipItem(id: "clip-4", sequence: 4, kind: .url, content: "https://example.com/4", domain: "example.com", createdAt: now, updatedAt: now),
            ClipItem(id: "clip-12", sequence: 12, kind: .text, content: "twelve", domain: nil, createdAt: now, updatedAt: now),
            ClipItem(id: "clip-24", sequence: 24, kind: .text, content: "twenty four", domain: nil, createdAt: now, updatedAt: now)
        ]

        XCTAssertEqual(SpeakableID.resolve("clip-4", in: items)?.id, "clip-4")
        XCTAssertEqual(SpeakableID.resolve("CLIP 4", in: items)?.id, "clip-4")
        XCTAssertEqual(SpeakableID.resolve("4", in: items)?.id, "clip-4")
        XCTAssertEqual(SpeakableID.resolve("#4", in: items)?.id, "clip-4")
        XCTAssertEqual(SpeakableID.resolve("clip four", in: items)?.id, "clip-4")
        XCTAssertEqual(SpeakableID.resolve("clip twelve", in: items)?.id, "clip-12")
        XCTAssertEqual(SpeakableID.resolve("clip twenty four", in: items)?.id, "clip-24")
        XCTAssertEqual(SpeakableID.resolve("클립 12", in: items)?.id, "clip-12")
        XCTAssertNil(SpeakableID.resolve("clip-99", in: items))
    }

    func testURLVsTextClassification() {
        let u1 = ClipClassifier.classify("  https://github.com/apple/swift/pull/1  ")
        XCTAssertEqual(u1?.kind, .url)
        XCTAssertEqual(u1?.domain, "github.com")
        XCTAssertEqual(u1?.normalizedContent, "https://github.com/apple/swift/pull/1")

        let u2 = ClipClassifier.classify("http://localhost:3000/api/health")
        XCTAssertEqual(u2?.kind, .url)
        XCTAssertEqual(u2?.domain, "localhost:3000")

        // Multiline text containing URL should be text, not URL
        let t1 = ClipClassifier.classify("Check this PR:\nhttps://github.com/apple/swift")
        XCTAssertEqual(t1?.kind, .text)
        XCTAssertNil(t1?.domain)

        // Unsafe or non-HTTP schemes are treated strictly as plain text
        let t2 = ClipClassifier.classify("javascript:alert(1)")
        XCTAssertEqual(t2?.kind, .text)

        let t3 = ClipClassifier.classify("file:///etc/passwd")
        XCTAssertEqual(t3?.kind, .text)

        XCTAssertNil(ClipClassifier.classify("   \n\t  "))
    }

    func testPasteboardPrivacyFiltering() {
        XCTAssertTrue(PasteboardPrivacyFilter.shouldIgnorePasteboardTypes(["public.utf8-plain-text", "org.nspasteboard.TransientType"]))
        XCTAssertTrue(PasteboardPrivacyFilter.shouldIgnorePasteboardTypes(["org.nspasteboard.ConcealedType"]))
        XCTAssertTrue(PasteboardPrivacyFilter.shouldIgnorePasteboardTypes(["org.nspasteboard.AutoGeneratedType"]))
        XCTAssertTrue(PasteboardPrivacyFilter.shouldIgnorePasteboardTypes(["com.agilebits.onepassword"]))
        XCTAssertTrue(PasteboardPrivacyFilter.shouldIgnorePasteboardTypes(["com.apple.security.concealed"]))
        XCTAssertFalse(PasteboardPrivacyFilter.shouldIgnorePasteboardTypes(["public.utf8-plain-text", "public.html"]))

        let oversized = String(repeating: "a", count: PasteboardPrivacyFilter.maxContentUTF8Bytes + 10)
        XCTAssertFalse(PasteboardPrivacyFilter.isAllowedPayloadSize(oversized))
        XCTAssertTrue(PasteboardPrivacyFilter.isAllowedPayloadSize("hello"))
    }

    func testPersistencePermissionsCapPauseDeleteAndClear() throws {
        let url = makeTempStoreURL()
        defer { try? FileManager.default.removeItem(at: url.deletingLastPathComponent()) }

        let store = ClipStore(fileURL: url)
        store.setMaxItems(5)
        for i in 1...7 {
            store.ingest("item \(i)")
        }

        // Verify cap enforced and newest 5 retained
        let ids = store.list().map(\.id)
        XCTAssertEqual(ids, ["clip-7", "clip-6", "clip-5", "clip-4", "clip-3"])

        // Verify file permissions are 0600
        let attrs = try FileManager.default.attributesOfItem(atPath: url.path)
        let perms = (attrs[.posixPermissions] as? NSNumber)?.intValue
        XCTAssertEqual(perms, 0o600)

        // Verify fresh store reload from disk
        let reloaded = ClipStore(fileURL: url)
        XCTAssertEqual(reloaded.list().map(\.id), ["clip-7", "clip-6", "clip-5", "clip-4", "clip-3"])

        // Pause ignores new ingests
        reloaded.setPaused(true)
        XCTAssertEqual(reloaded.ingest("ignored while paused"), .ignoredPaused)
        XCTAssertNil(reloaded.list().first(where: { $0.content == "ignored while paused" }))

        // Resume allows new ingests
        reloaded.setPaused(false)
        if case .inserted(let resumed) = reloaded.ingest("after resume") {
            XCTAssertEqual(resumed.id, "clip-8")
        } else {
            XCTFail("Expected insert after resume")
        }

        // Delete single item
        XCTAssertTrue(reloaded.delete(id: "clip-6"))
        XCTAssertNil(reloaded.get(idOrSpoken: "clip-6"))

        // Clear removes items but keeps sequence monotonic
        reloaded.clear()
        XCTAssertTrue(reloaded.list().isEmpty)
        if case .inserted(let afterClear) = reloaded.ingest("fresh after clear") {
            XCTAssertEqual(afterClear.id, "clip-9")
        } else {
            XCTFail("Expected monotonic sequence after clear")
        }
    }

    func testLocalizationCompletenessForEnglishAndKorean() {
        let original = L10n.overrideLocaleIdentifier
        defer { L10n.overrideLocaleIdentifier = original }

        for key in L10n.requiredKeys {
            L10n.overrideLocaleIdentifier = "en"
            let enValue = L10n.tr(key)
            XCTAssertNotEqual(enValue, key, "Missing English localization for key: \(key)")
            XCTAssertFalse(enValue.isEmpty, "Empty English localization for key: \(key)")

            L10n.overrideLocaleIdentifier = "ko"
            let koValue = L10n.tr(key)
            XCTAssertNotEqual(koValue, key, "Missing Korean localization for key: \(key)")
            XCTAssertFalse(koValue.isEmpty, "Empty Korean localization for key: \(key)")
        }

        L10n.overrideLocaleIdentifier = "ko"
        XCTAssertEqual(L10n.tr("status.live"), "수신 중")
        XCTAssertEqual(L10n.tr("inspector.chars_count", 42), "42자")
        L10n.overrideLocaleIdentifier = "en"
        XCTAssertEqual(L10n.tr("status.live"), "Live")
        XCTAssertEqual(L10n.tr("inspector.chars_count", 42), "42 chars")

        // Also validate the .lproj Localizable.strings files used inside ClipVoice.app
        let packageRoot = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .deletingLastPathComponent()
        for lang in ["en", "ko"] {
            let stringsURL = packageRoot
                .appendingPathComponent("Sources/ClipVoiceCore/Resources/\(lang).lproj/Localizable.strings")
            let dict = NSDictionary(contentsOf: stringsURL) as? [String: String]
            XCTAssertNotNil(dict, "Could not load \(lang).lproj/Localizable.strings")
            for key in L10n.requiredKeys {
                XCTAssertNotNil(dict?[key], "Missing key '\(key)' in \(lang).lproj/Localizable.strings")
                XCTAssertFalse((dict?[key] ?? "").isEmpty, "Empty value for '\(key)' in \(lang).lproj/Localizable.strings")
            }
        }
    }

    func testMCPActivityWatermarkPreservesSubsecondFractionAndIgnoresPrelaunchMarkers() throws {
        let url = makeTempStoreURL()
        defer { try? FileManager.default.removeItem(at: url.deletingLastPathComponent()) }

        // Pre-launch signal written at .800s before startup at .850s
        let prelaunchTime = Date(timeIntervalSince1970: 1_700_000_000.800)
        let startupTime = Date(timeIntervalSince1970: 1_700_000_000.850)
        let freshFractionTime = Date(timeIntervalSince1970: 1_700_000_000.900)

        MCPActivitySignal.emit(operation: .listClips, storeFileURL: url, now: prelaunchTime)
        let watermark = MCPActivityWatermark(storeFileURL: url, now: startupTime)

        // Pre-launch marker must remain ignored on startup poll.
        XCTAssertNil(watermark.poll())

        // Another stale pre-launch timestamp (even with a different eventID) must be rejected.
        let staleOther = MCPActivityEvent(eventID: "stale-2", operation: .getClip, timestamp: Date(timeIntervalSince1970: 1_700_000_000.849))
        XCTAssertNil(watermark.acceptIfFresh(staleOther))

        // Fresh signal within the same whole second (.900 vs .850) must preserve fraction 0.9 across encode/decode and trigger.
        MCPActivitySignal.emit(operation: .getClip, storeFileURL: url, now: freshFractionTime)
        let decoded = try XCTUnwrap(MCPActivitySignal.readLatest(for: url))
        XCTAssertEqual(decoded.timestamp.timeIntervalSince1970, 1_700_000_000.900, accuracy: 0.0001)

        let accepted = try XCTUnwrap(watermark.poll())
        XCTAssertEqual(accepted.operation, .getClip)
        XCTAssertEqual(accepted.timestamp.timeIntervalSince1970, 1_700_000_000.900, accuracy: 0.0001)

        // Repeated poll of the same eventID must not re-fire.
        XCTAssertNil(watermark.poll())
    }
}
