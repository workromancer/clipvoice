    func testStableIDInvarianceAcrossNewestFirstReorders() throws {
        let url = makeTempStoreURL()
        defer { try? FileManager.default.removeItem(at: url.deletingLastPathComponent()) }

        let store = ClipStore(fileURL: url)
        let r1 = store.ingest("https://github.com/workromancer/clipvoice")
        let r2 = store.ingest("swift test --parallel")
        let r3 = store.ingest("https://docs.swift.org/swift-book/")

        guard case .inserted(let c1) = r1,
              case .inserted(let c2) = r2,
              case .inserted(let c3) = r3 else {
            return XCTFail("Expected all 3 ingests to insert new items")
        }

        XCTAssertEqual(c1.id, "clip-1")
        XCTAssertEqual(c2.id, "clip-2")
        XCTAssertEqual(c3.id, "clip-3")

        // Newest-first order
        XCTAssertEqual(store.list().map(\.id), ["clip-3", "clip-2", "clip-1"])

        // Re-copying clip-1 bumps it to top while preserving its stable ID
        let bump = store.ingest("https://github.com/workromancer/clipvoice")
        guard case .bumpedExisting(let bumped) = bump else {
            return XCTFail("Expected duplicate ingest to bump existing item")
        }
        XCTAssertEqual(bumped.id, "clip-1")
        XCTAssertEqual(store.list().map(\.id), ["clip-1", "clip-3", "clip-2"])

        // Adding a 4th item assigns clip-4 and leaves existing IDs intact
        let r4 = store.ingest("fourth snippet")
        guard case .inserted(let c4) = r4 else {
            return XCTFail("Expected 4th insert")
        }
        XCTAssertEqual(c4.id, "clip-4")
        XCTAssertEqual(store.list().map(\.id), ["clip-4", "clip-1", "clip-3", "clip-2"])
    }

